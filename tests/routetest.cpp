/**********************************************************************
Проверка вывода года для даты выхода — прежде всего на Новый год.
***********************************************************************/
#include <cstdio>

#include "../android/RouteTime.h"

static int bad = 0;

static void check (const char *what, int got, int want)
{
	if (got == want)
		printf ("  ok   %s = %d\n", what, got);
	else {
		printf ("  ОШИБКА %s = %d, ожидалось %d\n", what, got, want);
		++bad;
	}
}

int main ()
{
	printf ("год для даты выхода:\n");

	// Обычный случай: прогноз и выход в одном месяце.
	check ("прогноз 10.09.2026, выход 12.09",
	       yearForStart (2026, 9, 10, 9, 12), 2026);

	// Прогноз в конце декабря, выход уже в январе — следующий год.
	check ("прогноз 31.12.2026, выход 02.01",
	       yearForStart (2026, 12, 31, 1, 2), 2027);
	check ("прогноз 28.12.2026, выход 05.01",
	       yearForStart (2026, 12, 28, 1, 5), 2027);

	// Прогноз в начале января, выход 31 декабря — прошлый год.
	check ("прогноз 03.01.2027, выход 31.12",
	       yearForStart (2027, 1, 3, 12, 31), 2026);

	// Тот же день — год не трогаем.
	check ("прогноз 31.12.2026, выход 31.12",
	       yearForStart (2026, 12, 31, 12, 31), 2026);

	// Високосный февраль.
	check ("прогноз 28.02.2028, выход 29.02",
	       yearForStart (2028, 2, 28, 2, 29), 2028);

	printf (bad == 0 ? "ВСЁ СОШЛОСЬ\n" : "ЕСТЬ ОШИБКИ\n");
	return bad;
}
