/**********************************************************************
MAKGrib для Android — год для даты выхода.

На колёсах маршрута только число и месяц: год штурману выбирать незачем,
маршрут прокладывают на ближайшие дни. Но число с месяцем повторяются
каждый год, и год приходится выводить — по сроку прогноза, который
загружен. Правило одно: берём тот год, при котором выход оказывается
ближе всего к прогнозу. Это само собой разбирает и Новый год: прогноз
от 31 декабря и выход 2 января — это следующий год, а прогноз от 3
января и выход 31 декабря — прошлый.

Заголовок нарочно без Qt: правило проверяется тестом на настольной
машине, без сборки под Android.
***********************************************************************/
#ifndef ROUTETIME_H
#define ROUTETIME_H

// Номер дня по григорианскому календарю (алгоритм Хиннанта). Нужен лишь
// затем, чтобы вычесть одну дату из другой.
inline long civilDays (int y, int m, int d)
{
	y -= (m <= 2) ? 1 : 0;
	long era = (y >= 0 ? y : y - 399) / 400;
	unsigned yoe = unsigned (y - era * 400);
	unsigned doy = unsigned ((153*(m + (m > 2 ? -3 : 9)) + 2)/5 + d - 1);
	unsigned doe = yoe*365 + yoe/4 - yoe/100 + doy;
	return era * 146097L + long (doe) - 719468L;
}

//---------------------------------------------------------------------
// Год для выхода, выбранного числом и месяцем, при сроке прогноза
// baseY/baseM/baseD.
inline int yearForStart (int baseY, int baseM, int baseD,
                         int wantM, int wantD)
{
	long base = civilDays (baseY, baseM, baseD);
	long want = civilDays (baseY, wantM, wantD);
	// Больше десяти месяцев вперёд — значит, это прошлый год; столько же
	// назад — значит, следующий.
	if (want - base > 300)
		return baseY - 1;
	if (base - want > 300)
		return baseY + 1;
	return baseY;
}

#endif
